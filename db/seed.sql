INSERT INTO orders (customer_id, employee_id, order_date, required_date, shipped_date, status,
                    shipping_address_id, billing_address_id, subtotal, discount_amount, tax_amount, shipping_cost, total_amount, currency, notes)
SELECT
  ((i-1) % 200) + 1 AS customer_id,
  ((i-1) % 90) + 11  AS employee_id,
  TIMESTAMP '2023-01-01' + ((i * 43) % 730 || ' days')::interval + ((i*7 % 24) || ' hours')::interval,
  DATE '2023-01-15' + ((i * 43) % 730) + 14,
  CASE WHEN i % 10 < 7
       THEN DATE '2023-01-10' + ((i * 43) % 730) + (i % 5) + 2
       ELSE NULL END,
  CASE i % 10
    WHEN 0 THEN 'delivered'
    WHEN 1 THEN 'delivered'
    WHEN 2 THEN 'delivered'
    WHEN 3 THEN 'shipped'
    WHEN 4 THEN 'shipped'
    WHEN 5 THEN 'processing'
    WHEN 6 THEN 'confirmed'
    WHEN 7 THEN 'pending'
    WHEN 8 THEN 'cancelled'
    ELSE        'refunded'
  END,
  ((i-1) % 350) + 1,  -- shipping_address_id
  ((i-1+1) % 350) + 1, -- billing_address_id (offset so they differ)
