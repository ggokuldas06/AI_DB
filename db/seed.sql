), 0);


UPDATE orders o
SET subtotal = COALESCE(item_totals.line_sum, o.subtotal)
FROM (
  SELECT order_id, SUM(line_total) AS line_sum
  FROM order_items
  GROUP BY order_id
) item_totals
WHERE o.order_id = item_totals.order_id;
